"""
gen.py -- generate Pinocchio's code-generated dynamics, to benchmark against.

Traces RNEA, ABA and CRBA symbolically with pinocchio.casadi and emits the
straight-line C that CasADi produces from the expression graph: no loops, no
model traversal, every operation for one specific robot spelled out. That is
the fastest thing a general-purpose library can hand you, so it is the right
thing to measure against.

Also emits cg_data.h: one random configuration per robot in both index
conventions, plus reference outputs computed by Pinocchio itself, so the C
harness compares both implementations against the same third party rather
than against each other.

    python3 gen.py --urdf-root /path/to/bard [-o generated]

Needs pinocchio with the casadi bindings. Either a conda env that has them
(`conda install -c conda-forge pinocchio casadi`) or the Dockerfile beside
this script.
"""

import argparse, os, sys
import numpy as np
import casadi as ca
import pinocchio as pin
import pinocchio.casadi as cpin

ROBOTS = {
    "spine": ("tests/spine.urdf", True),
    "xarm7": ("examples/example_robots/xarm_description/urdf/xarm7.urdf", False),
    "go2":   ("examples/example_robots/go2_description/urdf/go2.urdf", True),
}


def fmt(v):
    """A C float literal that is always a float literal: 0 is not 0f."""
    s = f"{float(v):.9g}"
    if "." not in s and "e" not in s and "E" not in s and "n" not in s:
        s += ".0"
    return s + "f"


def c_array(name, vals, per_line=6):
    out = [f"static const float {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per_line):
        chunk = ", ".join(fmt(v) for v in vals[i:i+per_line])
        out.append("    " + chunk + ("," if i + per_line < len(vals) else ""))
    out.append("};")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--urdf-root", required=True)
    ap.add_argument("-o", "--out", default=os.path.join(os.path.dirname(__file__), "generated"))
    ap.add_argument("--robots", default="spine,xarm7,go2")
    args = ap.parse_args()
    os.makedirs(args.out, exist_ok=True)
    want = args.robots.split(",")

    rng = np.random.default_rng(20260821)
    header = ["/* Generated by gen.py -- do not edit. */",
              "#ifndef CG_DATA_H", "#define CG_DATA_H", ""]
    listing = []

    for name in want:
        rel, floating = ROBOTS[name]
        path = os.path.join(args.urdf_root, rel)
        model = (pin.buildModelFromUrdf(path, pin.JointModelFreeFlyer())
                 if floating else pin.buildModelFromUrdf(path))
        data = model.createData()

        # --- symbolic tracing -> C ---------------------------------------
        cm = cpin.Model(model); q = ca.SX.sym("q", model.nq)
        v = ca.SX.sym("v", model.nv); u = ca.SX.sym("u", model.nv)
        built = {}
        d = cm.createData(); cpin.rnea(cm, d, q, v, u)
        built["rnea"] = ca.Function(f"{name}_rnea", [q, v, u], [d.tau])
        d = cm.createData(); cpin.aba(cm, d, q, v, u)
        built["aba"] = ca.Function(f"{name}_aba", [q, v, u], [d.ddq])
        d = cm.createData(); cpin.crba(cm, d, q)
        built["crba"] = ca.Function(f"{name}_crba", [q], [d.M])

        for kind, f in built.items():
            cg = ca.CodeGenerator(f"{name}_{kind}.c",
                                  {"casadi_real": "float", "casadi_int": "int",
                                   "with_header": False, "with_mem": False, "main": False})
            cg.add(f)
            cg.generate(args.out + os.sep)
            sz = os.path.getsize(os.path.join(args.out, f"{name}_{kind}.c"))
            listing.append(f"{name:6s} {kind:5s} nq={model.nq:2d} nv={model.nv:2d} "
                           f"ops={f.n_instructions():6d}  C={sz/1024:7.1f} KB")

        # --- one configuration, both conventions, reference outputs ------
        nq, nv = model.nq, model.nv
        qv = pin.randomConfiguration(model) if not floating else None
        if floating:
            qv = np.zeros(nq)
            qv[0:3] = rng.uniform(-0.3, 0.3, 3)
            quat = rng.normal(size=4); quat /= np.linalg.norm(quat)
            qv[3:7] = quat                       # pinocchio: x y z w
            qv[7:] = rng.uniform(-1.0, 1.0, nq - 7)
        else:
            qv = rng.uniform(-1.0, 1.0, nq)
        vv = rng.uniform(-1.0, 1.0, nv)
        av = rng.uniform(-1.0, 1.0, nv)
        tv = rng.uniform(-2.0, 2.0, nv)

        tau_ref = pin.rnea(model, data, qv, vv, av)
        ddq_ref = pin.aba(model, data, qv, vv, tv)
        pin.crba(model, data, qv)
        M = np.array(data.M); M = np.triu(M) + np.triu(M, 1).T

        U = name.upper()
        header.append(f"/* ---- {name}: nq={nq} nv={nv}"
                      f"{' floating' if floating else ''} ---- */")
        header.append(f"#define CG_{U}_NQ {nq}")
        header.append(f"#define CG_{U}_NV {nv}")
        header.append(c_array(f"cg_{name}_q", qv))          # pinocchio order
        if floating:
            # RobotDynamics: [x y z qw qx qy qz], scalar first
            base = np.concatenate([qv[0:3], [qv[6]], qv[3:6]])
            header.append(c_array(f"rd_{name}_qbase", base))
            header.append(c_array(f"rd_{name}_qjoints", qv[7:]))
        else:
            header.append(c_array(f"rd_{name}_qjoints", qv))
        header.append(c_array(f"cg_{name}_v", vv))
        header.append(c_array(f"cg_{name}_a", av))
        header.append(c_array(f"cg_{name}_tau_in", tv))
        header.append(c_array(f"cg_{name}_tau_ref", tau_ref))
        header.append(c_array(f"cg_{name}_ddq_ref", ddq_ref))
        header.append(c_array(f"cg_{name}_M_ref", M.flatten(order="C")))
        header.append("")

    header += ["#endif /* CG_DATA_H */"]
    with open(os.path.join(args.out, "cg_data.h"), "w") as fh:
        fh.write("\n".join(header) + "\n")

    print("\n".join(listing))
    print(f"\nwrote {args.out}/cg_data.h and the generated sources")


if __name__ == "__main__":
    sys.exit(main())
